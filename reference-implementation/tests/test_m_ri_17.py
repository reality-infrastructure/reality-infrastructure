"""M-RI-17 acceptance tests: belief pass over the contested set.

Pins the frozen preregistration and every discretionary declaration it
makes (mass assignments, alias predicate source, placeholder list,
frozen input manifest), the golden artifacts (byte-identical
regeneration), the Dolton known-answer commitment, and the contract
MUSTs (absence never reported as conflict; per-observation provenance;
mandated per-parcel wording; Recorder banners carried).
"""
from __future__ import annotations

